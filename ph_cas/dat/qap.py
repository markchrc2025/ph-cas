"""B28, B62: the QAP for the 1601-EQ, the annual 1604-E and the MAP for the 1600-VT.

Verified on 16 Nov 2026 against the BIR's own Alphalist Data Entry and Validation
module 7.4: the golden files in ph_cas/tests/golden/alphalist/ were generated by its
Data Entry module from dummy data and pass its Validation module; this writer
reproduces them byte for byte (test_b62_alphalist_golden).

What the module does, and so do we:
- The branch code is 4 digits (writer.branch4); the validator rejects 5.
- A name field is quoted when it has a value and an empty field with no quotes
  when blank (a company has no last, first or middle name; a person has no
  registered name). The withholding agent's registered name in the header is quoted.
- The QAP is monthly: the Data Entry module captures each month of the quarter
  and writes one file per month (TIN + branch + MMYYYY + 1601EQ.DAT), each with
  that month's rows. A month with no payee gives no file: the validator rejects a
  header with no detail ("No Detail Record found in file!").
- QAP Schedule 1 rows are by payee and ATC, sorted by TIN then ATC and numbered in
  that order; C1 totals income and tax. Schedule 2 (D2, C2) is written only when
  there are exempt payees.
- The 1604-E adds the year by payee and ATC, sorted by TIN then ATC (D3, C3 with
  the total withheld; D4, C4 with the total income).
- MAP rows are sorted by registered name, then last, first and middle name; the
  ATC is followed by an empty field.
- The rate is the ATC's rate, two decimals.
- Names drop the characters the validator refuses (writer.clean_name).
"""

import frappe
from frappe import _
from frappe.utils import add_months, flt, get_first_day, get_last_day, getdate

from ph_cas.dat.writer import (
    agent,
    clean_name,
    file_bytes,
    file_name,
    party_fields,
    record,
    store,
)

# Schedule 2 (exempt from withholding, subject to income tax): the payee's own
# income tax ATC, the same codes the 1701 and 1702 use. The validator accepts any
# income tax ATC here.
NO_WITHHOLDING_ATC = {"Individual": "II012", "Non-individual": "IC010"}
VAT_RATE = 12.0


def _withheld(company, start, end) -> list[dict]:
    rows = frappe.db.sql(
        """select supplier as party, ph_ewt_atc as atc, max(ph_ewt_rate) as rate, sum(ph_ewt_base) as income, sum(ph_ewt_amount) as tax
           from `tabPurchase Invoice` where company = %s and docstatus = 1 and posting_date between %s and %s
             and ifnull(ph_ewt_atc, '') != '' and ph_ewt_amount > 0 group by supplier, ph_ewt_atc""",
        (company, start, end), as_dict=True)
    rows += frappe.db.sql(
        """select party, ph_ewt_advance_atc as atc, 0 as rate, sum(paid_amount) as income, sum(ph_ewt_on_advance) as tax
           from `tabPayment Entry` where company = %s and party_type = 'Supplier' and docstatus = 1 and posting_date between %s and %s
             and ifnull(ph_ewt_advance_atc, '') != '' and ph_ewt_on_advance > 0 group by party, ph_ewt_advance_atc""",
        (company, start, end), as_dict=True)
    merged = {}
    for r in rows:
        d = merged.setdefault((r.party, r.atc), {"income": 0.0, "tax": 0.0, "rate": 0.0})
        d["income"] += flt(r.income)
        d["tax"] += flt(r.tax)
        d["rate"] = max(d["rate"], flt(r.rate))
    out = []
    for (party, atc), d in merged.items():
        p = party_fields("Supplier", party)
        rate = d["rate"] or (flt(d["tax"] / d["income"] * 100, 2) if d["income"] else 0)
        out.append({**p, "atc": atc, "income": d["income"], "tax": d["tax"], "rate": rate, "payee_type": frappe.get_cached_value("Supplier", party, "ph_payee_type") or "Non-individual"})
    out.sort(key=lambda x: (x["tin"], x["atc"]))
    return out


def _not_withheld(company, start, end) -> list[dict]:
    rows = frappe.db.sql(
        """select supplier as party, sum(base_net_total) as income from `tabPurchase Invoice`
           where company = %s and docstatus = 1 and posting_date between %s and %s and ph_no_withholding = 1 group by supplier""",
        (company, start, end), as_dict=True)
    out = []
    for r in rows:
        p = party_fields("Supplier", r.party)
        pt = frappe.get_cached_value("Supplier", r.party, "ph_payee_type") or "Non-individual"
        out.append({**p, "atc": NO_WITHHOLDING_ATC[pt], "income": flt(r.income)})
    out.sort(key=lambda x: (x["tin"], x["atc"]))
    return out


NAME_KINDS = ["qn", "qn", "qn", "qn"]


def _names(r):
    if r["registered_name"]:
        return [r["registered_name"], "", "", ""]
    return ["", r["last"], r["first"], r["middle"]]


def _company(company):
    return frappe.get_cached_doc("Company", company)


def qap_file(a: dict, period_end, s1: list[dict], s2: list[dict]) -> bytes:
    """One month's QAP: HQAP, then D1 and C1 when there are withheld payees, then D2 and
    C2 when there are exempt payees."""
    lines = [record(["HQAP", "H1601EQ", a["tin"], a["branch"], a["name"], period_end, a["rdo"]], ["u", "u", "u", "u", "q", "p", "u"])]
    if s1:
        ti = tw = 0.0
        for i, r in enumerate(s1, 1):
            lines.append(record(["D1", "1601EQ", i, r["tin"], r["branch"], *_names(r), period_end, r["atc"], r["rate"], r["income"], r["tax"]], ["u", "u", "i", "u", "u", *NAME_KINDS, "p", "u", "n", "n", "n"]))
            ti += r["income"]
            tw += r["tax"]
        lines.append(record(["C1", "1601EQ", a["tin"], a["branch"], period_end, ti, tw], ["u", "u", "u", "u", "p", "n", "n"]))
    if s2:
        t2 = 0.0
        for i, r in enumerate(s2, 1):
            lines.append(record(["D2", "1601EQ", i, r["tin"], r["branch"], *_names(r), period_end, r["atc"], r["income"]], ["u", "u", "i", "u", "u", *NAME_KINDS, "p", "u", "n"]))
            t2 += r["income"]
        lines.append(record(["C2", "1601EQ", a["tin"], a["branch"], period_end, t2], ["u", "u", "u", "u", "p", "n"]))
    return file_bytes(lines)


def build_1601eq(company, start, end) -> list[tuple[str, bytes, int]]:
    """The QAP for the quarter (or any run of months) from start to end: one file per
    month that has payees, as the BIR module writes it. [(file name, content, rows)]."""
    a = agent(company)
    c = _company(company)
    out = []
    month = get_first_day(getdate(start))
    last = getdate(end)
    while month <= last:
        m_end = min(get_last_day(month), last)
        s1, s2 = _withheld(company, month, m_end), _not_withheld(company, month, m_end)
        if s1 or s2:
            out.append((file_name(c.tax_id, c.ph_branch_code, m_end, "1601EQ"), qap_file(a, m_end, s1, s2), len(s1) + len(s2)))
        month = add_months(month, 1)
    return out


def annual_file(a: dict, year_end, s3: list[dict], s4: list[dict]) -> bytes:
    lines = [record(["H1604E", a["tin"], a["branch"], year_end, "N", 0, a["rdo"]], ["u", "u", "u", "d", "u", "i", "u"])]
    tw = 0.0
    for i, r in enumerate(s3, 1):
        lines.append(record(["D3", "1604E", a["tin"], a["branch"], year_end, i, r["tin"], r["branch"], *_names(r), r["atc"], r["income"], r["rate"], r["tax"]], ["u", "u", "u", "u", "d", "i", "u", "u", *NAME_KINDS, "u", "n", "n", "n"]))
        tw += r["tax"]
    lines.append(record(["C3", "1604E", a["tin"], a["branch"], year_end, tw], ["u", "u", "u", "u", "d", "n"]))
    ti = 0.0
    for i, r in enumerate(s4, 1):
        lines.append(record(["D4", "1604E", a["tin"], a["branch"], year_end, i, r["tin"], r["branch"], *_names(r), r["atc"], r["income"]], ["u", "u", "u", "u", "d", "i", "u", "u", *NAME_KINDS, "u", "n"]))
        ti += r["income"]
    lines.append(record(["C4", "1604E", a["tin"], a["branch"], year_end, ti], ["u", "u", "u", "u", "d", "n"]))
    return file_bytes(lines)


def build_1604e(company, year: int):
    start, end = f"{year}-01-01", f"{year}-12-31"
    a = agent(company)
    s3, s4 = _withheld(company, start, end), _not_withheld(company, start, end)
    c = _company(company)
    return file_name(c.tax_id, c.ph_branch_code, end, "1604E", kind="annual"), annual_file(a, end, s3, s4), len(s3) + len(s4)


def _map_key(r):
    return (r["registered_name"], r["last"], r["first"], r["middle"], r["tin"], r["atc"])


def map_file(a: dict, period_end, rows: list[dict]) -> bytes:
    lines = [record(["HMAP", "H1600VT", a["tin"], a["branch"], a["name"], period_end, a["rdo"]], ["u", "u", "u", "u", "q", "p", "u"])]
    ti = tw = 0.0
    for i, r in enumerate(sorted(rows, key=_map_key), 1):
        lines.append(record(["DMAP", "D1600VT", i, r["tin"], r["branch"], *_names(r), period_end, r["atc"], "", r["rate"], r["income"], r["tax"]], ["u", "u", "i", "u", "u", *NAME_KINDS, "p", "u", "e", "n", "n", "n"]))
        ti += r["income"]
        tw += r["tax"]
    lines.append(record(["CMAP", "C1600VT", a["tin"], a["branch"], period_end, ti, tw], ["u", "u", "u", "u", "p", "n", "n"]))
    return file_bytes(lines)


def build_1600vt(company, start, end):
    a = agent(company)
    rows = frappe.db.sql(
        """select supplier as party, ph_rc_atc as atc, sum(ph_rc_base) as income, sum(ph_rc_vat) as tax from `tabPurchase Invoice`
           where company = %s and docstatus = 1 and posting_date between %s and %s and ifnull(ph_rc_atc, '') != '' group by supplier, ph_rc_atc""",
        (company, start, end), as_dict=True)
    data = []
    for r in rows:
        s = frappe.get_cached_doc("Supplier", r.party)
        if s.get("ph_tin") or s.get("tax_id"):
            p = party_fields("Supplier", r.party)
        else:  # a non-resident provider has no Philippine TIN
            p = {"tin": "000000000", "branch": "0000", "registered_name": clean_name(s.get("ph_registered_name") or s.supplier_name or r.party), "last": "", "first": "", "middle": ""}
        data.append({**p, "atc": r.atc, "income": flt(r.income), "tax": flt(r.tax), "rate": VAT_RATE})
    c = _company(company)
    return file_name(c.tax_id, c.ph_branch_code, end, "1600VT"), map_file(a, end, data), len(data)


STATUS = {"1601EQ": "verified", "1604E": "verified", "1600VT": "verified"}


@frappe.whitelist()
def generate(company: str, form: str, period_start: str, period_end: str):
    """Write the form's alphalist file(s) as PH Alphalist File records. The 1601-EQ gives
    one file per month with payees (a list of names, empty when the quarter had none);
    the 1604-E and 1600-VT give one name, or None when there is no payee: the validator
    rejects a file with no detail ("No Detail Record found in file!"), so none is written."""
    frappe.has_permission("PH Alphalist File", "create", throw=True)
    if form == "1601EQ":
        files = build_1601eq(company, period_start, period_end)
    elif form == "1604E":
        files = [build_1604e(company, getdate(period_end).year)]
    elif form == "1600VT":
        files = [build_1600vt(company, period_start, period_end)]
    else:
        frappe.throw(_("Unknown form {0}.").format(form))
    frappe.flags.ph_dat_writer = True
    try:
        names = []
        for name, content, n in files:
            if not n:
                continue
            ps, pe = (get_first_day(_period_of(name)), _period_of(name)) if form == "1601EQ" else (period_start, period_end)
            names.append(store(company, form, ps, pe, name, content, STATUS[form], n))
    finally:
        frappe.flags.ph_dat_writer = False
    if form == "1601EQ":
        return names
    return names[0] if names else None


def _period_of(qap_name: str):
    """The month a QAP file covers, from its name (TIN9 + BC4 + MMYYYY + 1601EQ.DAT)."""
    mm, yyyy = int(qap_name[13:15]), int(qap_name[15:19])
    return get_last_day(f"{yyyy}-{mm:02d}-01")


def unknown_atcs() -> list[str]:
    """ATCs the engine uses that the current Alphalist module does not list.

    Empty since the BIR patched module 7.4: WV080, WV090, WV100 and WV110 (July 2025,
    after RMO 13-2025 and 27-2025) and WI/WC 840, 850 and 860 (tax advisory of
    18 Nov 2025, patch on bir.gov.ph > Downloadables). Clients must run the patched
    module. Add a code here when the engine uses one the module lacks."""
    known_missing: set[str] = set()
    used = {r[0] for r in frappe.db.sql("select distinct ph_ewt_atc from `tabPurchase Invoice` where ifnull(ph_ewt_atc,'') != ''")}
    used |= {r[0] for r in frappe.db.sql("select distinct ph_rc_atc from `tabPurchase Invoice` where ifnull(ph_rc_atc,'') != ''")}
    return sorted(used & known_missing)

STATUS = "verified"


def setup():
    from frappe.custom.doctype.custom_field.custom_field import create_custom_fields

    create_custom_fields({"Purchase Invoice": IMPORT_FIELDS}, ignore_validate=True, update=True)


def _clean(text) -> str:
    """Upper case, no quotes or commas, single spaces (RELIEF's 'clean special character')."""
    return re.sub(r"\s+", " ", str(text or "").replace('"', " ").replace(",", " ")).strip().upper()


def _with_zip(line: str, zipcode) -> str:
    z = _clean(zipcode)
    return f"{line} {z}".strip() if z and not line.endswith(z) else line


def _party(doctype, name):
    d = frappe.get_cached_doc(doctype, name)
    tin = re.sub(r"\D", "", d.get("ph_tin") or d.get("tax_id") or "") or "000000000"
    if d.get("ph_payee_type") == "Individual":
        names = ["", _clean(d.get("ph_last_name")), _clean(d.get("ph_first_name")), _clean(d.get("ph_middle_name"))]
    else:
        names = [_clean(d.get("ph_registered_name") or d.get("customer_name") or d.get("supplier_name") or name), "", "", ""]
    return tin, names, _clean(d.get("ph_address_line1")), _with_zip(_clean(d.get("ph_address_line2")), d.get("ph_zip"))


def _require_addresses(doctype: str, merged: dict, parties: dict):
    """The RELIEF validator rejects a row with neither address line ("Supplier Address is empty")."""
    missing = sorted(parties[tin] for tin, m in merged.items() if not (m["a1"] or m["a2"]))
    if missing:
        frappe.throw(_("Add a registered address to these {0}s before generating the summary list (the BIR RELIEF validator rejects a row without one): {1}").format(_(doctype).lower(), ", ".join(missing)))


def _owner_address(c) -> tuple[str, str]:
    """Address 1 and 2 of the header: the first line of the registered address,
    then the rest with the ZIP code (RELIEF joins substreet, street and barangay,
    then district, city and ZIP)."""
    lines = [_clean(x) for x in (c.get("ph_registered_address") or "").splitlines() if _clean(x)]
    a1 = lines[0] if lines else ""
    a2 = _with_zip(" ".join(lines[1:]), c.get("ph_zip"))
    if not a1:
        frappe.throw(_("Set the registered address of {0} (Company > Philippine details): the BIR RELIEF validator rejects a summary list without the owner's address.").format(c.name))
    return a1, a2


def _sort_key(item):
    tin, m = item
    return (*m["names"], tin)


HEADER_KINDS = ["u", "u", "q", "q", "q", "q", "q", "q", "q", "q"]
NAME_KINDS = ["qn", "qn", "qn", "qn"]


def owner(company: str) -> dict:
    """The owner block every RELIEF header starts with."""
    c = frappe.get_cached_doc("Company", company)
    a = agent(company)
    a1, a2 = _owner_address(c)
    if a["individual"]:
        names = ["", _clean(c.get("ph_last_name")), _clean(c.get("ph_first_name")), _clean(c.get("ph_middle_name"))]
    else:
        names = [_clean(a["name"]), "", "", ""]
    return {"tin": a["tin"], "names": names, "trade": _clean(c.get("ph_business_style")), "a1": a1, "a2": a2, "rdo": a["rdo"], "fiscal_month": 12}


def _head(kind: str, o: dict) -> list:
    return ["H", kind, o["tin"], *o["names"], o["trade"], o["a1"], o["a2"]]


def sales_file(o: dict, merged: dict, end) -> bytes:
    """merged: TIN -> {names: [reg, last, first, middle], a1, a2, exempt, zero, taxable, vat}."""
    keys = ("exempt", "zero", "taxable", "vat")
    tot = {k: round(sum(flt(m[k]) for m in merged.values()), 2) for k in keys}
    lines = [record([*_head("S", o), *(tot[k] for k in keys), o["rdo"], end, o["fiscal_month"]], [*HEADER_KINDS, "n", "n", "n", "n", "u", "d", "i"])]
    for tin, m in sorted(merged.items(), key=_sort_key):
        lines.append(record(["D", "S", tin, *m["names"], m["a1"], m["a2"], *(m[k] for k in keys), o["tin"], end], ["u", "u", "q", *NAME_KINDS, "q", "q", "nz", "nz", "nz", "nz", "u", "d"]))
    return file_bytes(lines)


def purchases_file(o: dict, merged: dict, end, noncreditable: float = 0.0) -> bytes:
    """merged: TIN -> {names, a1, a2, exempt, zero, services, capital, goods, vat}."""
    keys = ("exempt", "zero", "services", "capital", "goods", "vat")
    tot = {k: round(sum(flt(m[k]) for m in merged.values()), 2) for k in keys}
    noncreditable = round(flt(noncreditable), 2)
    lines = [record([*_head("P", o), *(tot[k] for k in keys), round(tot["vat"] - noncreditable, 2), noncreditable, o["rdo"], end, o["fiscal_month"]], [*HEADER_KINDS, "n", "n", "n", "n", "n", "n", "n", "n", "u", "d", "i"])]
    for tin, m in sorted(merged.items(), key=_sort_key):
        lines.append(record(["D", "P", tin, *m["names"], m["a1"], m["a2"], *(m[k] for k in keys), o["tin"], end], ["u", "u", "q", *NAME_KINDS, "q", "q", "nz", "nz", "nz", "nz", "nz", "nz", "u", "d"]))
    return file_bytes(lines)


def importations_file(o: dict, rows: list, end) -> bytes:
    """rows (in date order): {entry_no, assessed, seller, imported, country, dutiable, charges, exempt, taxable, vat, or_no, paid}."""
    if not rows:
        return b""
    keys = ("dutiable", "charges", "exempt", "taxable", "vat")
    tot = {k: round(sum(flt(r[k]) for r in rows), 2) for k in keys}
    lines = [record([*_head("I", o), *(tot[k] for k in keys), o["rdo"], end, o["fiscal_month"]], [*HEADER_KINDS, "n", "n", "n", "n", "n", "u", "d", "i"])]
    for r in rows:
        lines.append(record(["D", "I", r["entry_no"], r["assessed"] or end, r["seller"], r["imported"] or end, r["country"], *(r[k] for k in keys), r["or_no"], r["paid"] or end, o["tin"], end],
                            ["u", "u", "q", "d", "q", "d", "q", "nz", "nz", "nz", "nz", "nz", "q", "d", "u", "d"]))
    return file_bytes(lines)


def _fname(company, letter, end):
    c = frappe.get_cached_doc("Company", company)
    d = getdate(end)
    return f"{tin9(c.tax_id)}{letter}{d.month:02d}{d.year}.DAT"


def build_sales(company, start, end):
    o = owner(company)
    rows = frappe.db.sql(
        """select customer, sum(ph_exempt_sales) as exempt, sum(ph_zero_rated_sales) as zero, sum(ph_vatable_sales) as taxable, sum(ph_vat_amount) as vat
           from `tabSales Invoice` where company = %s and docstatus = 1 and posting_date between %s and %s group by customer""",
        (company, start, end), as_dict=True)
    merged, parties = {}, {}
    for r in rows:
        tin, names, a1, a2 = _party("Customer", r.customer)
        parties.setdefault(tin, r.customer)
        m = merged.setdefault(tin, {"names": names, "a1": a1, "a2": a2, "exempt": 0.0, "zero": 0.0, "taxable": 0.0, "vat": 0.0})
        for k in ("exempt", "zero", "taxable", "vat"):
            m[k] += flt(r[k])
    _require_addresses("Customer", merged, parties)
    return _fname(company, "S", end), sales_file(o, merged, end), len(merged)


def build_purchases(company, start, end):
    o = owner(company)
    from ph_cas.tax.rules import resolve

    rate = flt(resolve("vat", end, side="purchase").rate) or 12
    rows = frappe.db.sql(
        """select supplier, sum(ph_exempt_purchases) as exempt, sum(ph_input_vat_services) as vs, sum(ph_input_vat_capital) as vc, sum(ph_input_vat_goods) as vg
           from `tabPurchase Invoice` where company = %s and docstatus = 1 and posting_date between %s and %s and ifnull(ph_is_import, 0) = 0 group by supplier""",
        (company, start, end), as_dict=True)
    merged, parties = {}, {}
    for r in rows:
        tin, names, a1, a2 = _party("Supplier", r.supplier)
        parties.setdefault(tin, r.supplier)
        m = merged.setdefault(tin, {"names": names, "a1": a1, "a2": a2, "exempt": 0.0, "zero": 0.0, "services": 0.0, "capital": 0.0, "goods": 0.0, "vat": 0.0})
        m["exempt"] += flt(r.exempt)
        m["services"] += flt(r.vs) * 100 / rate
        m["capital"] += flt(r.vc) * 100 / rate
        m["goods"] += flt(r.vg) * 100 / rate
        m["vat"] += flt(r.vs) + flt(r.vc) + flt(r.vg)
    _require_addresses("Supplier", merged, parties)
    # non-creditable input VAT: the ratable share attributable to exempt sales (2550Q item 53), from the quarter's figures when computed
    noncred = 0.0
    fig = frappe.db.get_value("PH Tax Return Figures", {"company": company, "form": "2550Q", "period_start": start, "period_end": end}, "name")
    if fig:
        noncred = frappe.get_doc("PH Tax Return Figures", fig).figure("53B")
    return _fname(company, "P", end), purchases_file(o, merged, end, noncred), len(merged)


def build_importations(company, start, end):
    o = owner(company)
    bills = frappe.get_all("Purchase Invoice", filters={"company": company, "docstatus": 1, "ph_is_import": 1, "posting_date": ("between", [start, end])},
                           fields=["supplier_name", "ph_import_entry_no", "ph_import_assessment_date", "ph_import_date", "ph_import_country", "ph_import_dutiable_value", "ph_import_charges", "ph_exempt_purchases", "ph_input_vat_import", "ph_import_or_no", "ph_import_payment_date"],
                           order_by="ph_import_assessment_date, ph_import_entry_no, posting_date")
    rows = [{
        "entry_no": _clean(b.ph_import_entry_no), "assessed": b.ph_import_assessment_date, "seller": _clean(b.supplier_name), "imported": b.ph_import_date,
        "country": _clean(b.ph_import_country), "dutiable": flt(b.ph_import_dutiable_value), "charges": flt(b.ph_import_charges), "exempt": flt(b.ph_exempt_purchases),
        "taxable": flt(b.ph_import_dutiable_value) + flt(b.ph_import_charges) - flt(b.ph_exempt_purchases), "vat": flt(b.ph_input_vat_import),
        "or_no": _clean(b.ph_import_or_no), "paid": b.ph_import_payment_date,
    } for b in bills]
    return _fname(company, "I", end), importations_file(o, rows, end), len(rows)


def months(start, end) -> list[tuple]:
    """(first day, last day) of each month from start to end: the summary list is
    one file per month, three per quarterly submission (RDO answer 11)."""
    from frappe.utils import add_months, get_first_day, get_last_day

    out, d, end = [], get_first_day(start), getdate(end)
    while d <= end:
        out.append((d, get_last_day(d)))
        d = add_months(d, 1)
    return out


@frappe.whitelist()
def generate(company: str, kind: str, period_start: str, period_end: str) -> str:
    frappe.has_permission("PH Alphalist File", "create", throw=True)
    builder = {"S": build_sales, "P": build_purchases, "I": build_importations}[kind]
    name, content, n = builder(company, period_start, period_end)
    frappe.flags.ph_dat_writer = True
    try:
        return store(company, f"RELIEF-{kind}", period_start, period_end, name, content, STATUS, n)
    finally:
        frappe.flags.ph_dat_writer = False
